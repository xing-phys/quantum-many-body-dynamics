"""Consolidate source bibliographies without losing their provenance.

DOI/arXiv identity, not title similarity, controls deduplication. The original
four bibliographies remain available. Alias replacement is limited to citations.
"""
from pathlib import Path
import json, re
ROOT=Path(__file__).resolve().parents[1]
SOURCES=['core','thermal','transport','information']
def entries(text):
    out=[];pos=0
    while (m:=re.search(r'@(\w+)\s*\{\s*([^,]+),',text[pos:])):
        start=pos+m.start(); body=pos+m.end();i=body;depth=1
        while i<len(text) and depth:
            if text[i]=='\\': i+=2;continue
            if text[i]=='{':depth+=1
            elif text[i]=='}':depth-=1
            i+=1
        if depth:raise ValueError('Unbalanced BibTeX entry '+m[2])
        raw=text[start:i];fields={};p=body
        while p<i-1:
            n=re.match(r'\s*,?\s*([A-Za-z][\w-]*)\s*=\s*',text[p:i])
            if not n:break
            name=n[1].lower();p+=n.end();begin=p
            if text[p]=='{':
                p+=1;begin=p;d=1
                while p<i and d:
                    if text[p]=='\\':p+=2;continue
                    if text[p]=='{':d+=1
                    elif text[p]=='}':d-=1
                    p+=1
                value=text[begin:p-1]
            elif text[p]=='"':
                p+=1;begin=p
                while p<i and (text[p]!='"' or text[p-1]=='\\'):p+=1
                value=text[begin:p];p+=1
            else:
                while p<i and text[p] not in ',}':p+=1
                value=text[begin:p]
            fields[name]=value.strip()
        out.append({'key':m[2].strip(),'kind':m[1].lower(),'raw':raw,'fields':fields})
        pos=i
    return out
records=[]
for source in SOURCES:
    for r in entries((ROOT/f'references/{source}.bib').read_text()):
        r['source']=source;records.append(r)
parent=list(range(len(records)))
def find(i):
    while parent[i]!=i:parent[i]=parent[parent[i]];i=parent[i]
    return i
def union(i,j):parent[find(i)]=find(j)
seen={}
for i,r in enumerate(records):
    f=r['fields'];identities=['key:'+r['key']]
    doi=re.sub(r'^https?://(?:dx\.)?doi.org/','',f.get('doi',''),flags=re.I).lower().rstrip('.')
    if doi:identities.append('doi:'+doi)
    arxiv=f.get('eprint','')
    if not arxiv:
        m=re.search(r'arxiv.org/(?:abs|pdf)/([^?#]+)',f.get('url',''))
        if m:arxiv=m[1]
    arxiv=re.sub(r'(?:v\d+)?(?:\.pdf)?$','',arxiv)
    if arxiv:identities.append('arxiv:'+arxiv.lower())
    for ident in identities:
        if ident in seen:union(i,seen[ident])
        else:seen[ident]=i
groups={}
for i,r in enumerate(records):groups.setdefault(find(i),[]).append(r)
aliases={};canonical=[]
for group in groups.values():
    # Prefer a full published record over arXiv's short misc export.
    best=max(group,key=lambda r:(bool(r['fields'].get('journal')),bool(r['fields'].get('doi')),len(r['fields'])))
    best=dict(best);best['origins']=sorted({r['source'] for r in group})
    canonical.append(best)
    for r in group:aliases[r['key']]=best['key']
canonical.sort(key=lambda r:r['key'])
(ROOT/'references/all.bib').write_text('% Generated by scripts/prepare_references.py from source ledgers.\n\n'+'\n\n'.join(r['raw'] for r in canonical)+'\n')
(ROOT/'references/aliases.json').write_text(json.dumps(aliases,indent=2,ensure_ascii=False)+'\n')
(ROOT/'references/metadata.json').write_text(json.dumps(canonical,indent=2,ensure_ascii=False)+'\n')
for p in ROOT.glob('*.qmd'):
    text=p.read_text()
    text=re.sub(r'@([\w][\w:.-]*)',lambda m:'@'+aliases.get(m[1],m[1]),text)
    p.write_text(text)
def plain(s):
    return s.replace('{','').replace('}','').replace('|','\\|').replace('\n',' ')
rows=['## Complete selected-source index','',
      'The table lists the selected sources once each. Source-group labels identify',
      'which evidence ledger records their investigation. Citation aliases and the',
      'original bibliographies are preserved in the repository; identity-based',
      'deduplication uses DOI or arXiv identifiers, not fuzzy title matching.','',
      '| Source | Year | Role / evidence ledger |', '|'+'-'*68+'|'+'-'*8+'|'+'-'*24+'|']
for r in sorted(canonical,key=lambda r:(r['fields'].get('year',''),r['key'])):
    f=r['fields'];url=f.get('url') or 'https://doi.org/'+f.get('doi','')
    title=plain(f.get('title',r['key']))
    groups=', '.join(r['origins'])
    rows.append(f"| [{title}]({url}) [@{r['key']}] | {f.get('year','')} | {groups} |")
(ROOT/'research/source-index.qmd').write_text('\n'.join(rows)+'\n')
print(f'{len(records)} records -> {len(canonical)} unique selected sources; {sum(k!=v for k,v in aliases.items())} citation aliases.')
